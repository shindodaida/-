create table if not exists public.site_settings (
  key text primary key,
  value text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.characters (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  display_order integer not null default 1 check (display_order > 0),
  description text not null default '',
  illustration_price integer check (illustration_price is null or illustration_price >= 0),
  live2d_price integer check (live2d_price is null or live2d_price >= 0),
  full_price integer check (full_price is null or full_price >= 0),
  price_note text not null default '',
  status text not null default 'preparing' check (status in ('preparing','available','sold')),
  is_published boolean not null default false,
  face_image_url text not null,
  full_image_url text not null,
  video_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.characters add column if not exists video_url text;
create index if not exists characters_display_idx on public.characters(is_published,display_order);

create table if not exists public.character_interests (
  character_id uuid not null references public.characters(id) on delete cascade,
  visitor_id uuid not null,
  created_at timestamptz not null default now(),
  primary key(character_id,visitor_id)
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_id uuid not null unique,
  event_name text not null check(event_name in ('page_view','character_view','interest_click','inquiry_click')),
  session_id uuid not null,
  character_id uuid references public.characters(id) on delete set null,
  page text not null default '/',
  referrer text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  occurred_at timestamptz not null default now()
);
create index if not exists analytics_events_time_idx on public.analytics_events(occurred_at desc);
create index if not exists analytics_events_character_idx on public.analytics_events(character_id,occurred_at desc) where character_id is not null;

