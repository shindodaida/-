create or replace function public.get_public_characters()
returns jsonb language sql stable security definer set search_path=pg_catalog as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',c.id,'name',c.name,'display_order',c.display_order,'description',c.description,
    'illustration_price',c.illustration_price,'live2d_price',c.live2d_price,
    'full_price',c.full_price,'price_note',c.price_note,'status',c.status,
    'is_published',c.is_published,'face_image_url',c.face_image_url,'full_image_url',c.full_image_url,
    'video_url',c.video_url,
    'interest_count',(select count(*) from public.character_interests i where i.character_id=c.id)
  ) order by c.display_order,c.created_at),'[]'::jsonb)
  from public.characters c where c.is_published
$$;
revoke all on function public.get_public_characters() from public;
grant execute on function public.get_public_characters() to anon,authenticated;

create or replace function public.toggle_site_interest(p_character_id uuid,p_visitor_id uuid)
returns jsonb language plpgsql security definer set search_path=pg_catalog as $$
declare active boolean; total bigint;
begin
  if not exists(select 1 from public.characters c where c.id=p_character_id and c.is_published and c.status='available') then raise exception '受付中ではありません'; end if;
  delete from public.character_interests where character_id=p_character_id and visitor_id=p_visitor_id;
  if found then active:=false; else insert into public.character_interests(character_id,visitor_id) values(p_character_id,p_visitor_id) on conflict do nothing; active:=true; end if;
  select count(*) into total from public.character_interests where character_id=p_character_id;
  return jsonb_build_object('active',active,'count',total);
end $$;
revoke all on function public.toggle_site_interest(uuid,uuid) from public;
grant execute on function public.toggle_site_interest(uuid,uuid) to anon,authenticated;

create or replace function public.track_site_event(p_event_id uuid,p_event_name text,p_session_id uuid,p_character_id uuid default null,p_page text default '/',p_referrer text default null,p_utm_source text default null,p_utm_medium text default null,p_utm_campaign text default null)
returns void language plpgsql security definer set search_path=pg_catalog as $$
begin
  if p_event_name not in ('page_view','character_view','interest_click','inquiry_click') then raise exception 'invalid event'; end if;
  if p_character_id is not null and not exists(select 1 from public.characters c where c.id=p_character_id and c.is_published) then raise exception 'invalid character'; end if;
  insert into public.analytics_events(event_id,event_name,session_id,character_id,page,referrer,utm_source,utm_medium,utm_campaign)
  values(p_event_id,p_event_name,p_session_id,p_character_id,left(coalesce(p_page,'/'),500),left(p_referrer,1000),left(p_utm_source,200),left(p_utm_medium,200),left(p_utm_campaign,200))
  on conflict(event_id) do nothing;
end $$;
revoke all on function public.track_site_event(uuid,text,uuid,uuid,text,text,text,text,text) from public;
grant execute on function public.track_site_event(uuid,text,uuid,uuid,text,text,text,text,text) to anon,authenticated;

create or replace function public.get_admin_analytics(p_period text default '30d')
returns jsonb language plpgsql stable security definer set search_path=pg_catalog as $$
declare start_at timestamptz; result jsonb;
begin
 if lower(coalesce(auth.jwt()->>'email',''))<>lower('YOUR_EMAIL@example.com') then raise exception '管理者のみ利用できます'; end if;
 start_at:=case p_period when '7d' then now()-interval '7 days' when '30d' then now()-interval '30 days' else '1970-01-01'::timestamptz end;
 select jsonb_build_object('totals',jsonb_build_object(
   'page_views',count(*) filter(where e.event_name='page_view'),
   'unique_visitors',count(distinct e.session_id) filter(where e.event_name='page_view'),
   'character_views',count(*) filter(where e.event_name='character_view'),
   'inquiries',count(*) filter(where e.event_name='inquiry_click')),
   'characters',coalesce((select jsonb_agg(jsonb_build_object('name',c.name,
     'views',(select count(*) from public.analytics_events x where x.character_id=c.id and x.event_name='character_view' and x.occurred_at>=start_at),
     'interests',(select count(*) from public.character_interests i where i.character_id=c.id),
     'inquiries',(select count(*) from public.analytics_events x where x.character_id=c.id and x.event_name='inquiry_click' and x.occurred_at>=start_at)) order by c.display_order) from public.characters c),'[]'::jsonb)
 ) into result from public.analytics_events e where e.occurred_at>=start_at;
 return result;
end $$;
revoke all on function public.get_admin_analytics(text) from public;
grant execute on function public.get_admin_analytics(text) to authenticated;

